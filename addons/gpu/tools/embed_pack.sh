#!/usr/bin/env sh
# Writes a .gpushader pack as a C array: embed_pack.sh <pack> <symbol>
set -eu

pack=$1
symbol=$2

command -v xxd >/dev/null 2>&1 || {
    echo "sigpu: xxd is required to embed shader packs" >&2
    exit 1
}

echo "/* Generated by make shaders from $(basename -- "$pack"). Do not edit manually. */"
printf 'static const unsigned char %s[] = {\n' "$symbol"
xxd -i < "$pack"
printf '};\n'
